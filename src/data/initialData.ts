export const getCategoryDefinition = (
  catId: string,
  customCategories?: CategoryDefinition[]
): CategoryDefinition => {
  const allCats = customCategories || defaultCategories;
  const found = allCats.find((c) => c.id === catId);
  if (found) return found;

  // Fallback for custom or unknown category
  return {
    id: catId,
    name: catId.replace(/_/g, ' ').replace(/\b\w/g, (l) => l.toUpperCase()),
    color: 'bg-teal-50 text-teal-700 border-teal-200',
    desc: 'Kategori kustom BOP RT',
    isCustom: true,
  };
};

